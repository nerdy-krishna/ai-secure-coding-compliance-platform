"""The single ingestion manifest: caps, skip reasons, and the submission guard.

The contract these tests hold:

* every file submitted is either accepted or skipped **with a reason** — the count
  of the two always equals what came in;
* the caps are limits, not silent truncation;
* a submission nothing can scan is refused up front instead of producing an empty
  scan, and a submission of nothing but vendored code says so explicitly.
"""

from __future__ import annotations

import pytest

from app.shared.lib import ingest_manifest as im

PY_SOURCE = "def handler(request):\n    return request.query\n"
GENERATED = "# Code generated by protoc-gen-python. DO NOT EDIT.\n\nclass Msg:\n    pass\n"


def test_mixed_submission_accounts_for_every_file() -> None:
    manifest = im.build_manifest(
        [
            ("src/app.py", PY_SOURCE),
            ("Dockerfile", "FROM python:3.12\n"),
            ("requirements.txt", "requests==2.31\n"),
            ("README.md", "# hi\n"),
            ("payload.bin", "\x00\x01\x02" * 10),
            ("empty.py", ""),
            ("comment_only.py", "# nothing here\n"),
            ("twice.py", "x = 1\n"),
            ("twice.py", "x = 2\n"),
            ("../escape.py", "x = 1\n"),
            ("notes.wibble", "hello\n"),
        ],
        source="upload",
    )

    counts = manifest.reason_counts()
    assert counts[im.SKIP_BINARY] == 1
    assert counts[im.SKIP_EMPTY] == 2
    assert counts[im.SKIP_DUPLICATE_PATH] == 1
    assert counts[im.SKIP_INVALID_PATH] == 1
    assert counts[im.SKIP_UNSUPPORTED_TYPE] == 1  # notes.wibble: no language, no scanner

    assert manifest.files_total == len(manifest.entries) + len(manifest.skipped)
    assert manifest.entries["src/app.py"].allowed_scanners == (
        "bandit",
        "semgrep",
        "gitleaks",
    )
    assert manifest.contents["twice.py"] == "x = 1\n"  # first copy wins
    assert ".." not in " ".join(manifest.entries)


def test_first_party_files_survive_inside_build_directories() -> None:
    manifest = im.build_manifest(
        [("build/handwritten.py", PY_SOURCE), ("dist/app.js", "var a = 1;\n")],
        source="git",
    )
    assert manifest.entries["build/handwritten.py"].role == "first_party_source"
    assert manifest.first_party == 2


def test_build_output_is_recognised_when_its_manifest_arrives_first() -> None:
    manifest = im.build_manifest(
        [("web/package.json", '{"name":"web"}'), ("web/dist/app.js", "var a = 1;\n")],
        source="git",
    )
    assert manifest.entries["web/dist/app.js"].role == "generated_asset"


def test_vendored_only_submission_is_first_party_free() -> None:
    files = [(f"node_modules/pkg_{i}/index.js", "module.exports = 1;\n") for i in range(50)]
    files.append(("web/dist/app.js", GENERATED))

    manifest = im.build_manifest(files, source="git")
    assert manifest.first_party == 0
    assert manifest.scannable == len(files)  # Gitleaks still reads them
    detail = manifest.vendor_only_detail()
    assert "None of the 51 submitted file(s) is your own source code" in detail
    assert "Scan vendor and generated files" in detail


def test_deep_vendor_scan_widens_the_allowed_scanners() -> None:
    path = "node_modules/pkg/index.js"
    plain = im.build_manifest([(path, "module.exports = 1;\n")], source="git")
    deep = im.build_manifest([(path, "module.exports = 1;\n")], source="git", deep_vendor_scan=True)

    assert plain.entries[path].allowed_scanners == ("gitleaks",)
    assert "semgrep" in deep.entries[path].allowed_scanners


def test_nothing_scannable_is_refused_with_a_reason_breakdown() -> None:
    manifest = im.build_manifest(
        [("payload.bin", "\x00\x01\x02" * 10), ("empty.py", "")], source="archive"
    )
    assert manifest.scannable == 0
    detail = manifest.rejection_detail()
    assert "None of the 2 submitted file(s) can be scanned" in detail
    assert "1 binary input" in detail and "1 empty input" in detail


def test_file_cap_skips_the_overflow_instead_of_truncating() -> None:
    files = [(f"src/m{i}.py", "x = 1\n") for i in range(30)]
    manifest = im.build_manifest(files, source="upload", max_files=10)

    assert len(manifest.entries) == 10
    assert manifest.reason_counts()[im.SKIP_FILE_LIMIT] == 20
    assert manifest.files_total == 30


def test_total_and_per_file_size_caps() -> None:
    total = im.build_manifest(
        [(f"src/big{i}.py", "x" * 100) for i in range(10)],
        source="upload",
        max_total_bytes=350,
    )
    assert total.reason_counts()[im.SKIP_TOTAL_SIZE] == 7

    per_file = im.build_manifest(
        [("src/huge.py", "x" * 500), ("src/ok.py", PY_SOURCE)], source="upload", max_file_bytes=100
    )
    assert per_file.reason_counts()[im.SKIP_FILE_SIZE] == 1
    assert "src/ok.py" in per_file.entries


def test_dict_items_match_the_readers_shape() -> None:
    manifest = im.build_manifest(
        [{"path": "src/x.kt", "content": "fun main() {}\n", "language": "kotlin"}], source="git"
    )
    assert manifest.entries["src/x.kt"].language == "kotlin"
    assert manifest.files_for_persistence() == [
        {"path": "src/x.kt", "content": "fun main() {}\n", "language": "kotlin"}
    ]


def test_summary_is_human_readable() -> None:
    manifest = im.build_manifest(
        [("src/app.py", PY_SOURCE), ("node_modules/a/i.js", "module.exports = 1;\n"), ("e.py", "")],
        source="archive",
    )
    summary = manifest.summary()
    assert summary["files_total"] == 3
    assert summary["files_scannable"] == 2
    assert summary["files_skipped"] == 1
    assert "Received 3 file(s) from archive" in summary["message"]
    assert summary["excluded_by_reason"] == {im.SKIP_EMPTY: 1}
    assert summary["roles"]["runtime_artifact"] == 1


def test_unsupported_item_shape_is_a_programming_error() -> None:
    with pytest.raises(TypeError):
        im.build_manifest([object()], source="upload")
