"""File-role classification and language/scanner capability.

These two tables are the only thing standing between "scan the user's code" and
"scan 6,500 files in node_modules", so each rule is asserted individually.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from app.shared.lib import ingest_manifest as im
from app.shared.lib.file_classification import classify_file, split_scanners
from app.shared.lib.language_registry import resolve, scanners_for

PY_SOURCE = "def handler(request):\n    return request.query\n"
GENERATED = "# Code generated by protoc-gen-python. DO NOT EDIT.\n\nclass Msg:\n    pass\n"
JQUERY = "/*! jQuery v3.6.0 | (c) OpenJS Foundation */\n!function(){}();\n"
MINIFIED = "var a=1;" * 4000


def role(path: str, content: str, submitted: set[str] | None = None) -> str:
    return classify_file(path, content, submitted_paths=submitted or {path})["role"]


@pytest.mark.parametrize(
    ("path", "content", "expected"),
    [
        # First-party source, including files whose *path* looks generated.
        ("src/app.py", PY_SOURCE, "first_party_source"),
        ("build/handwritten.py", PY_SOURCE, "first_party_source"),
        ("target/classes/Handwritten.java", "package a;\nclass H {}\n", "first_party_source"),
        ("src/entry.py", "#!/usr/bin/env python3\nprint('x')\n", "first_party_source"),
        ("Dockerfile", "FROM python:3.12\n", "first_party_source"),
        # Generated and third-party code, including files whose path does not say so.
        ("src/proto/msg_pb2.py", GENERATED, "generated_asset"),
        # A bare output directory is not evidence on its own — see the sibling test.
        ("dist/app.js", "var a=1;\n", "first_party_source"),
        ("static/js/jquery.min.js", JQUERY, "known_third_party_vendor"),
        ("node_modules/pkg/index.js", "module.exports = 1;\n", "runtime_artifact"),
        (".venv/lib/python3.12/site-packages/lib/mod.py", PY_SOURCE, "runtime_artifact"),
        ("src/__pycache__/mod.cpython-312.pyc", "binary-ish", "runtime_artifact"),
        ("web/dist/bundle.min.js", MINIFIED, "first_party_minified_bundle"),
        # Not auditable.
        ("poetry.lock", "[[package]]\n", "dependency_lockfile"),
        ("package-lock.json", "{}\n", "dependency_lockfile"),
        ("docs/empty.py", "", "empty"),
        ("docs/comments.py", "# only a comment\n", "empty"),
        ("assets/logo.png", "\x00\x89PNG\x00", "binary"),
    ],
)
def test_role(path: str, content: str, expected: str) -> None:
    assert role(path, content) == expected


def test_build_output_needs_a_build_manifest_sibling() -> None:
    """`dist/` on its own is not a reason to skip a file."""
    standalone = classify_file("dist/app.js", "var a=1;\n", submitted_paths={"dist/app.js"})
    assert standalone["role"] == "first_party_source"

    with_manifest = classify_file(
        "web/dist/app.js",
        "var a=1;\n",
        submitted_paths={"web/dist/app.js", "web/package.json"},
    )
    assert with_manifest["role"] == "generated_asset"


def test_binary_is_never_source() -> None:
    assert role("src/payload.py", "PK\x03\x04\x00\x00\x00") == "binary"


@pytest.mark.parametrize(
    ("path", "language"),
    [
        ("src/Main.kt", "kotlin"),
        ("src/lib.rs", "rust"),
        ("web/component.tsx", "typescript"),
        ("types.d.ts", "typescript"),
        ("Dockerfile", "dockerfile"),
        ("Makefile", "makefile"),
        ("Jenkinsfile", "groovy"),
        ("requirements.txt", "requirements"),
        ("infra/main.tf", "terraform"),
        (".env.production", "dotenv"),
        ("archive.tar.gz", None),  # archives are extracted at ingest, never classified
        ("whatever.wibble", None),
    ],
)
def test_language_resolution(path: str, language: str | None) -> None:
    assert resolve(path)[0] == language


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("src/app.py", ["bandit", "semgrep", "gitleaks"]),
        ("src/Main.kt", ["semgrep", "gitleaks"]),
        ("src/lib.rs", ["semgrep", "gitleaks"]),
        ("scripts/deploy.sh", ["gitleaks"]),
        ("requirements.txt", ["gitleaks"]),
        ("whatever.wibble", []),
    ],
)
def test_scanner_capability(path: str, expected: list[str]) -> None:
    assert scanners_for(path) == expected


def test_role_decides_whether_a_capable_scanner_runs() -> None:
    source = classify_file("src/app.py", PY_SOURCE)
    vendored = classify_file("vendor/lib.py", PY_SOURCE)
    generated = classify_file("src/proto/msg_pb2.py", GENERATED)

    assert split_scanners(["bandit", "semgrep", "gitleaks"], source) == (
        ["bandit", "semgrep", "gitleaks"],
        [],
    )
    assert split_scanners(["bandit", "semgrep", "gitleaks"], vendored) == (
        ["gitleaks"],
        ["bandit", "semgrep"],
    )
    assert split_scanners(["bandit", "semgrep", "gitleaks"], generated) == (
        ["gitleaks"],
        ["bandit", "semgrep"],
    )


def test_deep_vendor_scan_widens_the_scope() -> None:
    vendored = classify_file("node_modules/pkg/index.js", "module.exports = 1;\n")
    allowed, denied = split_scanners(["semgrep", "gitleaks"], vendored, deep_vendor_scan=True)
    assert "semgrep" in allowed and denied == []


def test_semgrep_languages_come_from_the_registry() -> None:
    """Rule selection reads the shared table, not a private extension list."""
    from app.infrastructure.scanners.semgrep_rules import derive_semgrep_languages

    assert derive_semgrep_languages(
        ["src/Main.kt", "src/lib.rs", "api/x.py", "infra/main.tf", "Dockerfile", "a.wibble"]
    ) == ["dockerfile", "hcl", "kotlin", "python", "rust"]
    assert derive_semgrep_languages(["a.wibble"]) == []


def test_large_tree_keeps_every_first_party_file(tmp_path: Path) -> None:
    """5,000 files: nothing of the user's is dropped, every exclusion has a reason."""
    files: list[tuple[str, str]] = []
    for index in range(300):
        files.append((f"src/module_{index}/handlers.py", PY_SOURCE))
    for index in range(200):
        files.append((f"build/kept_{index}.py", PY_SOURCE))
    for index in range(3000):
        files.append((f"node_modules/pkg_{index}/index.js", "module.exports = 1;\n"))
    for index in range(1000):
        files.append((f"web/dist/bundle_{index}.min.js", MINIFIED))
    for index in range(300):
        files.append((f"src/proto/msg_{index}_pb2.py", GENERATED))
    for index in range(200):
        files.append((f"docs/empty_{index}.py", ""))

    assert len(files) == 5000
    manifest = im.build_manifest(files, source="git")

    first_party = [
        entry.path for entry in manifest.entries.values() if entry.role == "first_party_source"
    ]
    assert len(first_party) == 500
    assert all(path in manifest.entries for path in first_party)

    # Every file is either accepted or skipped with a reason — never dropped.
    assert manifest.files_total == len(manifest.entries) + len(manifest.skipped)
    assert manifest.reason_counts() == {im.SKIP_EMPTY: 200}
    assert manifest.role_counts()["generated_asset"] == 300
    assert manifest.role_counts()["runtime_artifact"] == 3000
    assert manifest.scannable == len(manifest.entries)
